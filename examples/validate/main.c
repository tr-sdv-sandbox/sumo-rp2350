/* Visible life-sign that does not depend on USB-CDC actually being
 * connected to a host. Pico 2 / Waveshare RP2350-CAN both default to
 * the LED on GPIO 25 via PICO_DEFAULT_LED_PIN. If a future target has
 * no default, override at compile time with -DDIAG_LED_PIN=N. */
#ifndef DIAG_LED_PIN
#  ifdef PICO_DEFAULT_LED_PIN
#    define DIAG_LED_PIN PICO_DEFAULT_LED_PIN
#  else
#    define DIAG_LED_PIN 25
#  endif
#endif

static void led_init(void)
{
    gpio_init(DIAG_LED_PIN);
    gpio_set_dir(DIAG_LED_PIN, GPIO_OUT);
    gpio_put(DIAG_LED_PIN, 0);
}

static void led_set(int on) { gpio_put(DIAG_LED_PIN, on ? 1 : 0); }

static void blink_n(int n, int on_ms, int off_ms)
{
    for (int i = 0; i < n; i++) {
        led_set(1); sleep_ms(on_ms);
        led_set(0); sleep_ms(off_ms);
    }
}

/* Stage-marker: log + flush + LED pulse. When a later stage hangs,
 * the last LED pulse count tells us how far we got even with no
 * console attached. */
#define STAGE(n, msg) do {                              \
    printf("stage %d: %s\n", (n), (msg));               \
    fflush(stdout);                                     \
    sleep_ms(50);                                       \
    blink_n((n), 80, 80);                               \
    sleep_ms(200);                                      \
} while (0)

