/**
 * @file examples/validate/main.c
 * @brief Checkpoint-2: validate + stream-decrypt on RP2350.
 *
 *   1. validate the SUIT envelope (ES256, mbedtls/PSA — checkpoint 1)
 *   2. unwrap the COSE_Encrypt CEK with the device KEK (A128KW)
 *   3. stream ciphertext through psa_aead_update in small chunks
 *      (proves the decrypt path doesn't need the full image in RAM)
 *   4. verify the GCM tag and compare plaintext with expected.
 *
 * Three byte arrays are baked in: the envelope, the COSE_Encrypt
 * (encryption_info) bytes, the ciphertext, plus the expected
 * plaintext we compare against. Real apps would parse encryption_info
 * out of the validated manifest and pull ciphertext over a transport.
 *
 * Build the fixture set with:
 *
 *   sumo-tool build --signing-key sign.key \
 *     --component "ecu-a,firmware" --seq 2 \
 *     --vendor fa6b4a53d5ad5fdfbe9de663e4d41ffe \
 *     --class  1492af1425695e48bf429b2d51f2ab45 \
 *     --uri "file:///fw" --firmware fw.bin \
 *     --encrypt devkey.cose \
 *     --payload-output fw.enc \
 *     --output encfix.suit
 *
 * The KEK is the 16-byte symmetric key from devkey.cose's `k` field.
 *
 * SPDX-License-Identifier: Apache-2.0
 */
